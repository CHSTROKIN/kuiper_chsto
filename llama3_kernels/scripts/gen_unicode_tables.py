#!/usr/bin/env python3
"""Generates src/unicode_tables.h: the code points in \\p{L} and \\p{N}.

Run from llama3_kernels/:  python3 scripts/gen_unicode_tables.py
"""
import sys
import unicodedata


def ranges(major):
    out = []
    for cp in range(sys.maxunicode + 1):
        if unicodedata.category(chr(cp))[0] != major:
            continue
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def table(name, items):
    cells = [f"{{0x{a:X}, 0x{b:X}}}," for a, b in items]
    rows = ["    " + " ".join(cells[i:i + 4]) for i in range(0, len(cells), 4)]
    return f"constexpr Range {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


with open("src/unicode_tables.h", "w") as f:
    f.write(
        "// Generated by scripts/gen_unicode_tables.py "
        f"(Unicode {unicodedata.unidata_version}). Do not edit.\n"
        "#pragma once\n\n#include <cstdint>\n\n"
        "namespace llama3 {\nnamespace unicode {\n\n"
        "struct Range {\n  uint32_t first, last;  // inclusive\n};\n\n"
        + table("kLetters", ranges("L")) + "\n" + table("kNumbers", ranges("N"))
        + "\n}  // namespace unicode\n}  // namespace llama3\n"
    )
